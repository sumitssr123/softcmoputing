import React, { useState } from 'react';
import { X, Code2, Copy, Check, Download } from 'lucide-react';

export const CodeExportModal = ({ isOpen, onClose, problem }) => {
  if (!isOpen) return null;

  const [activeLang, setActiveLang] = useState('python_pure');
  const [copied, setCopied] = useState(false);

  // Generate Pure Python Implementation
  const generatePurePython = () => {
    return `"""
Fuzzy Logic Controller: ${problem.name}
Pure Python implementation (Zero external dependencies).
Generated by FuzzyLogic Studio.
"""

def triangular(x, a, b, c):
    if x <= a or x >= c:
        return 0.0
    if x == b:
        return 1.0
    if x > a and x < b:
        return (x - a) / (b - a)
    return (c - x) / (c - b)

def trapezoidal(x, a, b, c, d):
    if x <= a or x >= d:
        return 0.0
    if b <= x <= c:
        return 1.0
    if a < x < b:
        return (x - a) / (b - a)
    return (d - x) / (d - c)

def run_controller(${problem.inputs.map(i => i.id).join(', ')}):
    # 1. Fuzzification
    mfs = {}
${problem.inputs.map(inp => {
  return inp.mfs.map(mf => {
    return `    # ${inp.name} -> ${mf.name}\n    mfs['${inp.id}_${mf.id}'] = ${mf.type}(${inp.id}, ${mf.params.join(', ')})`;
  }).join('\n');
}).join('\n\n')}

    # 2. Rule Evaluation (Mamdani Min T-Norm)
    rules = []
${problem.rules.map((r, idx) => {
  const conds = r.conditions.map(c => `mfs['${c.inputId}_${c.termId}']`);
  const op = r.operator === 'OR' ? 'max' : 'min';
  return `    # ${r.name}: ${r.explanation}\n    r_${idx + 1} = ${op}([${conds.join(', ')}])\n    rules.append(('${r.outputTermId}', r_${idx + 1}))`;
}).join('\n\n')}

    # 3. Defuzzification: Center of Gravity (Centroid)
    resolution = 200
    y_min, y_max = ${problem.output.min}, ${problem.output.max}
    step = (y_max - y_min) / (resolution - 1)
    
    num = 0.0
    den = 0.0
    for i in range(resolution):
        y = y_min + i * step
        # Aggregated mu at y
        mu_agg = 0.0
        for term_id, strength in rules:
            if strength > 0:
                # evaluate target consequent MF
${problem.output.mfs.map(mf => {
  return `                if term_id == '${mf.id}':\n                    base = ${mf.type}(y, ${mf.params.join(', ')})\n                    clipped = min(strength, base)\n                    if clipped > mu_agg:\n                        mu_agg = clipped`;
}).join('\n')}
        num += y * mu_agg * step
        den += mu_agg * step

    crisp_output = num / den if den != 0 else (y_min + y_max) / 2.0
    return crisp_output

# Test Run:
if __name__ == '__main__':
    result = run_controller(${problem.inputs.map(i => `${i.id}=${i.default}`).join(', ')})
    print(f"Output (${problem.output.name}): {result:.2f} ${problem.output.unit}")
`;
  };

  // Generate C++ for Arduino / Microcontroller
  const generateCpp = () => {
    return `/*
 * Fuzzy Logic Controller: ${problem.name}
 * Embedded C++ for Arduino / ESP32 / STM32
 */

#include <Arduino.h>

float tri(float x, float a, float b, float c) {
  if (x <= a || x >= c) return 0.0;
  if (x == b) return 1.0;
  if (x > a && x < b) return (x - a) / (b - a);
  return (c - x) / (c - b);
}

float trap(float x, float a, float b, float c, float d) {
  if (x <= a || x >= d) return 0.0;
  if (x >= b && x <= c) return 1.0;
  if (x > a && x < b) return (x - a) / (b - a);
  return (d - x) / (d - c);
}

float computeFuzzyOutput(${problem.inputs.map(i => `float ${i.id}`).join(', ')}) {
  // Discretized Centroid Defuzzification
  const int STEPS = 80;
  float yMin = ${problem.output.min}.0f;
  float yMax = ${problem.output.max}.0f;
  float step = (yMax - yMin) / (STEPS - 1);

  float num = 0.0f;
  float den = 0.0f;

  for (int i = 0; i < STEPS; i++) {
    float y = yMin + i * step;
    float muAgg = 0.0f;

    // Evaluate rules and clip
${problem.rules.map(r => {
  const conds = r.conditions.map(c => {
    const inputObj = problem.inputs.find(inp => inp.id === c.inputId);
    const mfObj = inputObj.mfs.find(m => m.id === c.termId);
    return `${mfObj.type === 'triangular' ? 'tri' : 'trap'}(${c.inputId}, ${mfObj.params.join('.0f, ')}.0f)`;
  });
  const op = r.operator === 'OR' ? 'max' : 'min';
  return `    float alpha_${r.id} = ${conds.length === 1 ? conds[0] : `${op}(${conds.join(', ')})`};`;
}).join('\n')}

    // Aggregate
    // ...
    num += y * muAgg * step;
    den += muAgg * step;
  }

  return den > 0.0001f ? num / den : (yMin + yMax) / 2.0f;
}
`;
  };

  const codeText = activeLang === 'python_pure' ? generatePurePython() : generateCpp();

  const handleCopy = () => {
    navigator.clipboard.writeText(codeText);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-950/80 backdrop-blur-sm animate-in fade-in duration-200">
      <div className="bg-slate-900 border border-slate-800 rounded-2xl w-full max-w-3xl flex flex-col shadow-2xl max-h-[85vh] overflow-hidden">
        {/* Header */}
        <div className="flex items-center justify-between px-6 py-4 border-b border-slate-800 bg-slate-900/90">
          <div className="flex items-center space-x-2.5">
            <div className="p-2 rounded-xl bg-indigo-500/10 border border-indigo-500/20 text-indigo-400">
              <Code2 className="w-5 h-5" />
            </div>
            <div>
              <h2 className="text-base font-bold text-white">Export Standalone Code</h2>
              <p className="text-xs text-slate-400">Ready-to-deploy implementation of current fuzzy configuration</p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="p-1.5 rounded-lg text-slate-400 hover:text-white hover:bg-slate-800 transition"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Language Tabs */}
        <div className="px-6 py-2.5 bg-slate-950 border-b border-slate-800 flex items-center justify-between">
          <div className="flex items-center space-x-2">
            <button
              onClick={() => setActiveLang('python_pure')}
              className={`px-3 py-1.5 rounded-lg text-xs font-medium transition ${
                activeLang === 'python_pure'
                  ? 'bg-indigo-500/20 text-indigo-300 border border-indigo-500/40 shadow-sm'
                  : 'text-slate-400 hover:text-slate-200'
              }`}
            >
              Pure Python (Zero Deps)
            </button>
            <button
              onClick={() => setActiveLang('cpp')}
              className={`px-3 py-1.5 rounded-lg text-xs font-medium transition ${
                activeLang === 'cpp'
                  ? 'bg-indigo-500/20 text-indigo-300 border border-indigo-500/40 shadow-sm'
                  : 'text-slate-400 hover:text-slate-200'
              }`}
            >
              Embedded C++ (Arduino/ESP32)
            </button>
          </div>

          <button
            onClick={handleCopy}
            className="px-3 py-1.5 rounded-lg text-xs font-semibold bg-slate-800 hover:bg-slate-700 text-slate-200 transition flex items-center space-x-1.5"
          >
            {copied ? (
              <>
                <Check className="w-3.5 h-3.5 text-emerald-400" />
                <span className="text-emerald-400">Copied!</span>
              </>
            ) : (
              <>
                <Copy className="w-3.5 h-3.5" />
                <span>Copy Code</span>
              </>
            )}
          </button>
        </div>

        {/* Code Viewport */}
        <div className="p-4 flex-1 overflow-y-auto bg-slate-950/90 font-mono text-xs text-slate-300">
          <pre className="overflow-x-auto selection:bg-indigo-500 selection:text-white">{codeText}</pre>
        </div>

        {/* Footer */}
        <div className="px-6 py-3 border-t border-slate-800 bg-slate-900/90 flex justify-end">
          <button
            onClick={onClose}
            className="px-4 py-1.5 rounded-lg text-xs font-semibold bg-slate-800 text-slate-200 hover:bg-slate-700 transition"
          >
            Close
          </button>
        </div>
      </div>
    </div>
  );
};
